#!/usr/bin/env python3
"""Run real end-to-end VisionForge measurements against a running server.
Usage: python evaluate.py --url http://127.0.0.1:7860 --repeats 3
No scores are fabricated; failed or unavailable measurements remain blank.
"""
import argparse, csv, json, statistics, time
from pathlib import Path
import requests

PROMPTS = [
    "A red vintage motorcycle parked in a rainy Tokyo alley at night, cinematic photograph",
    "A small wooden cabin beside a lake surrounded by pine trees at sunrise, realistic landscape",
    "A ceramic coffee cup on a desk beside an open notebook and a green plant, natural window light",
    "A golden retriever running across a grassy field, action photograph, detailed fur",
    "A futuristic electric car on a mountain road at sunset, wide-angle photography",
]

def median(values):
    vals=[v for v in values if isinstance(v,(int,float))]
    return round(statistics.median(vals),2) if vals else None

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--url',default='http://127.0.0.1:7860')
    ap.add_argument('--repeats',type=int,default=3)
    ap.add_argument('--out',default='evaluation_results')
    args=ap.parse_args(); base=args.url.rstrip('/')
    health=requests.get(base+'/health',timeout=30); health.raise_for_status(); info=health.json()
    rows=[]
    # One warm-up per mode; excluded from reported measurements.
    for mode in ['fast','balanced','quality','auto']:
        for prompt_i,prompt in enumerate(PROMPTS):
            for pp in [False, True]:
                payload={'prompt':prompt,'mode':mode,'classical_enhance':pp,'seed':1000+prompt_i,'resolution':512}
                for run in range(-1,args.repeats):
                    started=time.perf_counter()
                    response=requests.post(base+'/generate',json=payload,timeout=900)
                    elapsed=(time.perf_counter()-started)*1000
                    response.raise_for_status(); data=response.json()
                    # Validate actual image payload rather than accepting metadata-only responses.
                    import base64
                    image=base64.b64decode(data['image'],validate=True)
                    if len(image)<1000: raise RuntimeError('Generated image payload unexpectedly small')
                    if run >= 0:
                        rows.append({'requested_mode':mode,'selected_mode':data.get('mode'),'steps':data.get('steps'),
                          'resolution':data.get('resolution'),'dtype':data.get('dtype'),'prompt_id':prompt_i+1,
                          'run':run+1,'classical_postprocess':pp,'wall_latency_ms':round(elapsed,1),
                          'server_generation_ms':data.get('generation_ms'),'clip_score':data.get('clip_score'),
                          'clip_eval_ms':data.get('clip_eval_ms'),'peak_gpu_memory_mb':data.get('peak_gpu_memory_mb'),
                          'process_rss_before_mb':data.get('process_rss_before_mb'),
                          'process_rss_after_mb':data.get('process_rss_after_mb'),
                          'system_ram_available_before_mb':data.get('system_ram_available_before_mb'),
                          'device':data.get('device'),'model':data.get('model'),'image_bytes':len(image)})
                print(f"Completed {mode} | prompt {prompt_i+1}/5 | classical={pp}")
    out=Path(args.out); out.mkdir(parents=True,exist_ok=True)
    with (out/'raw_runs.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=rows[0].keys()); w.writeheader(); w.writerows(rows)
    groups={}
    for mode in ['fast','balanced','quality','auto']:
      for pp in [False,True]:
        subset=[r for r in rows if r['requested_mode']==mode and r['classical_postprocess']==pp]
        groups[f'{mode}_classical_{str(pp).lower()}']={
          'runs':len(subset),'median_wall_latency_ms':median([r['wall_latency_ms'] for r in subset]),
          'median_generation_ms':median([r['server_generation_ms'] for r in subset]),
          'median_clip_score':median([r['clip_score'] for r in subset]),
          'median_clip_eval_ms':median([r['clip_eval_ms'] for r in subset]),
          'median_peak_gpu_memory_mb':median([r['peak_gpu_memory_mb'] for r in subset]),
          'median_process_rss_after_mb':median([r['process_rss_after_mb'] for r in subset]),
          'selected_modes':sorted(set(r['selected_mode'] for r in subset)),
          'resolutions':sorted(set(r['resolution'] for r in subset)),
          'device':info.get('device'),'model':info.get('model')}
    result={'health':info,'prompt_count':len(PROMPTS),'repeats_per_prompt':args.repeats,
            'warmup_runs_excluded':True,'summary':groups,'raw_csv':'raw_runs.csv'}
    (out/'summary.json').write_text(json.dumps(result,indent=2))
    md=['# VisionForge P3 T83 — Measured Evaluation Results','',
        '> Generated by evaluate.py from live API responses. Do not edit measurements manually.', '',
        f"- Device: `{info.get('device')}`",f"- Model: `{info.get('model')}`",
        f"- Prompts: {len(PROMPTS)}; repeats per prompt/profile: {args.repeats}; warm-ups excluded.",'',
        '| Requested profile | Classical postprocess | Selected mode(s) | Output size(s) | Median generation (ms) | Median CLIP cosine | Median peak GPU MB | Median process RAM after (MB) | Runs |',
        '|---|---:|---|---|---:|---:|---:|---:|---:|']
    for key,v in groups.items():
        mode,_,flag=key.split('_',2)
        def fmt(x): return 'N/A' if x is None else str(x)
        md.append(f"| {mode} | {flag} | {', '.join(v['selected_modes'])} | {', '.join(str(x) for x in v['resolutions'])} | {fmt(v['median_generation_ms'])} | {fmt(v['median_clip_score'])} | {fmt(v['median_peak_gpu_memory_mb'])} | {fmt(v['median_process_rss_after_mb'])} | {v['runs']} |")
    md += ['', '## Interpretation', '- CLIP cosine is a relative text-image alignment indicator, not a probability.',
           '- Compare profiles on the same hardware. Latency includes inference only in `server_generation_ms`; wall latency includes API overhead.',
           '- GPU memory is reported only on CUDA; CPU runs show N/A. Process RAM is a post-request snapshot, not peak RAM.',
           '- FID is not calculated: this prompt benchmark has no real-image reference distribution.',
           '- See `raw_runs.csv` and `summary.json` for per-run evidence.']
    (out/'eval_P3_T83.md').write_text('\n'.join(md)+'\n')
    print(f"Saved actual measurements to {out.resolve()}")
if __name__=='__main__': main()
